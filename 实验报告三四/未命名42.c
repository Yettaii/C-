#include<stdio.h>
//头文件 
int main()
//主函数开始 
{
	int x,y;
	//定义xy两个整型 
	printf("输入整数x:");
	//进行输入提示 
	scanf("%d",&x);
	//读取输入的整数储存到x的地址中 
	if(x<1){//判断x是否小于1（第一个分段函数） 
		y=x;//若x<1，y直接=x 
	}else if(x<10){//若x在1<=x<10区间内，（第二个分段函数） 
		y=2*x-1;//含题目要求计算y值 
	}else{//否则x>=10（第三个分段函数 
		y=3*x-11;//按题目要求计算y值 
	}
	printf("y的值为：%d\n",y);//输出计算的y值 

	return 0;//程序正常退出 
}
